// ─── Helpers ────────────────────────────────────────────────────────────

export function hasHardcodedCountry(countryCode: string): boolean {
  return countryCode.toUpperCase() in GEO_HARDCODED_SETS;
}

export function getCountrySets(countryCode: string): GeoSet[] | undefined {
  return GEO_HARDCODED_SETS[countryCode.toUpperCase()];
}

export function getSetCount(): number {
  return Object.keys(GEO_HARDCODED_SETS).length;
}

export function getTotalQuestionCount(): number {
  return Object.values(GEO_HARDCODED_SETS).reduce(
    (acc, sets) => acc + sets.reduce((s, set) => s + set.questions.length, 0),
    0
  );
}
